package j2pc.emit;

import j2pc.Options;
import j2pc.classfile.ClassFile;
import j2pc.classfile.Descriptor;
import j2pc.util.Log;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/** Renders a whole {@link ClassFile} as a Java compilation unit. */
public final class ClassEmitter {

    private final ClassFile cf;
    private final Options opts;
    private final SourceWriter out;
    private final NameRegistry names;
    private final TypeMapper types;
    /** Every class of the application, so supertypes can be inspected. */
    private final Map<String, ClassFile> universe;
    /** Extra members to append, for classes whose archive record is incomplete. */
    private final java.util.List<String> extraMembers;

    public ClassEmitter(ClassFile cf, Options opts, NameRegistry names, TypeMapper types,
                        Map<String, ClassFile> universe, java.util.List<String> extraMembers) {
        this.cf = cf;
        this.opts = opts;
        this.names = names;
        this.types = types;
        this.universe = universe;
        this.extraMembers = extraMembers == null ? java.util.List.of() : extraMembers;
        this.out = new SourceWriter(opts.indentUnit);
    }

    public String emit() {
        String internal = cf.name();
        String pkg = opts.packagePrefix.isEmpty() ? types.packageOf(internal) : opts.packagePrefix;
        String simple = types.simpleName(internal);
        out.line("// Generated by J2PC " + opts.version + " - J2ME static recompiler");
        out.line("// Original class: " + internal);
        String src = cf.sourceFile();
        if (src != null) {
            out.line("// Original source: " + src);
        }
        out.line("// Regenerate with: j2pc <application.jar>");
        out.blank();

        if (!pkg.isEmpty()) {
            out.line("package " + pkg + ";");
            out.blank();
        }

        // An enum has to be written as an enum declaration: Java forbids
        // extending java.lang.Enum directly.
        if (EnumEmitter.isEnum(cf)) {
            new EnumEmitter(cf, opts, out, names, types).emit();
            return out.toString();
        }

        StringBuilder decl = new StringBuilder();
        String mods = Modifiers.forClass(cf.access, opts);
        if (!mods.contains("abstract") && !cf.isInterface() && hasAbstractMethod()) {
            // The JVM allows a non-abstract class to declare abstract methods;
            // Java source does not.
            mods = "abstract " + mods;
        }
        if (!mods.isEmpty()) {
            decl.append(mods).append(' ');
        }
        boolean iface = cf.isInterface();
        if ((cf.access & ClassFile.ACC_ANNOTATION) != 0) {
            decl.append("@interface ");
        } else if (iface) {
            decl.append("interface ");
        } else {
            decl.append("class ");
        }
        decl.append(simple);

        String sup = cf.superName();
        if (sup != null && !"java/lang/Object".equals(sup)) {
            decl.append(" extends ").append(typeRef(sup));
        }
        String[] itfs = cf.interfaceNames();
        if (itfs.length > 0) {
            decl.append(iface ? " extends " : " implements ");
            for (int i = 0; i < itfs.length; i++) {
                if (i > 0) {
                    decl.append(", ");
                }
                decl.append(typeRef(itfs[i]));
            }
        }
        decl.append(" {");
        out.line(decl.toString());
        out.indent();

        boolean any = false;
        for (ClassFile.Member f : cf.fields) {
            if (!opts.includeSynthetic && f.isSynthetic()) {
                continue;
            }
            any = true;
            emitField(f);
        }

        for (ClassFile.Member m : cf.methods) {
            if (!opts.includeSynthetic && m.isSynthetic()) {
                continue;
            }
            if ("<clinit>".equals(m.name())) {
                continue;
            }
            any = true;
            emitMethod(m);
        }

        emitStaticInitializer();

        if (!cf.isAbstract() && !cf.isInterface()) {
            emitImplicitConstructorIfNeeded();
            emitMissingAbstractStubs();
        }

        emitExtraMembers();

        if (!any) {
            out.line("// no members");
        }

        out.outdent();
        out.line("}");
        return out.toString();
    }

    /**
     * Emits a constructor when the archive record has none.
     *
     * <p>Java inserts an implicit no-argument constructor that calls
     * {@code super()}. That only compiles when the superclass has such a
     * constructor; when the archive lost the record and the superclass takes
     * arguments, the implicit one fails to compile. The class could not be
     * instantiated on a handset either — a class file without a constructor
     * raises {@code NoSuchMethodError} — so a constructor that throws keeps both
     * the compilation and the behaviour, and says why.</p>
     */
    private void emitImplicitConstructorIfNeeded() {
        for (ClassFile.Member m : cf.methods) {
            if ("<init>".equals(m.name())) {
                return;
            }
        }
        ClassFile parent = universe.get(cf.superName());
        if (parent == null || hasNoArgConstructor(parent)) {
            // The implicit constructor javac inserts is exactly right.
            return;
        }
        out.blank();
        out.line("// The archive record of this class has no constructor.");
        out.line("// The superclass has no no-argument constructor, so the implicit one");
        out.line("// would not compile; instantiation failed on a handset as well.");
        out.line("public " + Names.simpleName(cf.name()) + "() {");
        out.indent();
        // Java still requires a super(...) call, so the cheapest superclass
        // constructor is called with default arguments before the failure. The
        // object is never returned, so its state does not matter.
        String[] cheapest = cheapestConstructor(parent);
        if (cheapest != null) {
            out.line("super(" + defaultArgs(cheapest) + ");");
        }
        out.line("throw new NoSuchMethodError(\"" + Names.external(cf.name())
                + " has no constructor\");");
        out.outdent();
        out.line("}");
    }

    /** Descriptor of the superclass constructor with the fewest arguments. */
    private static String[] cheapestConstructor(ClassFile owner) {
        String[] best = null;
        for (ClassFile.Member m : owner.methods) {
            if (!"<init>".equals(m.name()) || m.desc() == null) {
                continue;
            }
            String[] args = Descriptor.args(m.desc());
            if (best == null || args.length < best.length) {
                best = args;
            }
        }
        return best;
    }

    /** {@code null, 0, false} for each parameter of {@code args}. */
    private static String defaultArgs(String[] args) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < args.length; i++) {
            if (i > 0) {
                sb.append(", ");
            }
            String a = args[i];
            switch (a.charAt(0)) {
                case 'Z': sb.append("false"); break;
                case 'J': sb.append("0L"); break;
                case 'F': sb.append("0f"); break;
                case 'D': sb.append("0d"); break;
                case 'L':
                case '[':
                    sb.append("null");
                    break;
                default:
                    sb.append('0');
            }
        }
        return sb.toString();
    }

    private static boolean hasNoArgConstructor(ClassFile owner) {
        for (ClassFile.Member m : owner.methods) {
            if ("<init>".equals(m.name()) && "()V".equals(m.desc())) {
                return true;
            }
        }
        return false;
    }

    /** Appends the members that the archive record of this class is missing. */
    private void emitExtraMembers() {        if (extraMembers.isEmpty()) {
            return;
        }
        out.blank();
        out.line("// Members referenced elsewhere but absent from the original archive.");
        for (String line : extraMembers) {
            out.line(line);
        }
    }

    private boolean hasAbstractMethod() {
        for (ClassFile.Member m : cf.methods) {
            if ((m.access & ClassFile.ACC_ABSTRACT) != 0) {
                return true;
            }
        }
        return false;
    }

    /**
     * Emits stubs for abstract methods the class does not implement.
     *
     * <p>The JVM does not require a concrete class to implement every interface
     * method — calling a missing one raises {@code AbstractMethodError} at run
     * time. Java source does require it, so a stub that throws the same error
     * keeps both the compilation and the behaviour intact.</p>
     */
    private void emitMissingAbstractStubs() {
        Map<String, AbsSig> missing = new LinkedHashMap<>();
        // Platform ancestors first: an archive class may implement what a platform
        // interface declares, and the archive walk removes satisfied entries.
        collectPlatform(cf.superName(), missing);
        for (String itf : cf.interfaceNames()) {
            collectPlatform(itf, missing);
        }
        collectAbstract(cf.superName(), missing, 0);
        for (String itf : cf.interfaceNames()) {
            collectAbstract(itf, missing, 0);
        }
        for (ClassFile.Member m : cf.methods) {
            // Only a non-static method can satisfy an abstract instance method;
            // bytecode happily declares a static one with the same signature.
            if (!m.isStatic()) {
                missing.remove(m.name() + m.desc());
            }
        }
        if (missing.isEmpty()) {
            return;
        }
        Log.debug("%s: %d abstract method(s) not implemented: %s",
                cf.name(), missing.size(), missing.keySet());
        java.util.Set<String> usedNames = new java.util.HashSet<>();
        for (AbsSig sig : missing.values()) {
            // The stub must carry the name the declaring type gave the method,
            // otherwise it does not implement anything.
            String name = names.method(sig.owner(), sig.name(), sig.desc());
            String[] args = Descriptor.args(sig.desc());
            // Two distinct abstract methods can share a name and an arity —
            // `Code(byte[],String)` and `Code(Code,String)` are different overloads.
            // Only an identical Java signature would be a duplicate.
            java.util.List<String> argTypes = new java.util.ArrayList<>(args.length);
            for (String arg : args) {
                argTypes.add(types.ref(arg));
            }
            if (!usedNames.add(name + "(" + String.join(",", argTypes) + ")")) {
                continue;
            }
            out.blank();
            String ret = Descriptor.returnType(sig.desc());
            StringBuilder sb = new StringBuilder("public ");
            sb.append(types.ref(ret)).append(' ').append(name).append('(');
            for (int i = 0; i < argTypes.size(); i++) {
                if (i > 0) {
                    sb.append(", ");
                }
                sb.append(argTypes.get(i)).append(" arg").append(i);
            }
            sb.append(") {");
            out.line(sb.toString());
            out.indent();
            out.line("throw new AbstractMethodError(\"not implemented: "
                    + Names.external(sig.name()) + "\");");
            out.outdent();
            out.line("}");
        }
    }

    /** An abstract method that a concrete class still has to provide. */
    private record AbsSig(String name, String desc, String owner) {
    }

    /** Adds every abstract method reachable from {@code internal}, recursively. */
    private void collectAbstract(String internal, Map<String, AbsSig> out, int depth) {
        if (internal == null || depth > 16) {
            return;
        }
        ClassFile superType = universe.get(internal);
        if (superType == null) {
            return;
        }
        for (ClassFile.Member m : superType.methods) {
            if (m.name() == null || m.desc() == null) {
                continue;
            }
            String key = m.name() + m.desc();
            // An interface method without a body is abstract even when the
            // compiler forgot to set ACC_ABSTRACT, which old CLDC tools did.
            boolean abstractMethod = m.isAbstract()
                    || (superType.isInterface() && m.code() == null && !m.isStatic());
            if (abstractMethod) {
                out.putIfAbsent(key, new AbsSig(m.name(), m.desc(), internal));
            } else if (!m.isStatic()) {
                // A concrete instance implementation anywhere satisfies it.
                out.remove(key);
            }
        }
        collectAbstract(superType.superName(), out, depth + 1);
        for (String itf : superType.interfaceNames()) {
            collectAbstract(itf, out, depth + 1);
        }
    }

    /**
     * Adds the abstract methods of a platform type the archive does not contain.
     *
     * <p>{@code java.io.DataInput}, {@code javax.microedition.lcdui.CommandListener}
     * and friends are not in the universe, so the only way to know what a class
     * still owes them is to ask the running JVM. A type that cannot be loaded is
     * simply skipped: the class then compiles exactly as far as javac allows.</p>
     */
    private void collectPlatform(String internal, Map<String, AbsSig> out) {
        if (internal == null || universe.containsKey(internal)) {
            return;
        }
        Class<?> type;
        try {
            type = Class.forName(internal.replace('/', '.'), false,
                    ClassEmitter.class.getClassLoader());
        } catch (ClassNotFoundException | LinkageError | RuntimeException e) {
            return;
        }
        for (java.lang.reflect.Method m : type.getMethods()) {
            if (!java.lang.reflect.Modifier.isAbstract(m.getModifiers())) {
                continue;
            }
            String desc = descriptorOf(m);
            out.putIfAbsent(m.getName() + desc, new AbsSig(m.getName(), desc, internal));
        }
    }

    /** JVM descriptor of a reflective method. */
    private static String descriptorOf(java.lang.reflect.Method m) {
        StringBuilder sb = new StringBuilder("(");
        for (Class<?> p : m.getParameterTypes()) {
            sb.append(descriptorOf(p));
        }
        return sb.append(')').append(descriptorOf(m.getReturnType())).toString();
    }

    private static String descriptorOf(Class<?> c) {
        if (c.isArray()) {
            return c.getName().replace('.', '/');
        }
        if (!c.isPrimitive()) {
            return "L" + c.getName().replace('.', '/') + ";";
        }
        if (c == boolean.class) {
            return "Z";
        }
        if (c == byte.class) {
            return "B";
        }
        if (c == char.class) {
            return "C";
        }
        if (c == short.class) {
            return "S";
        }
        if (c == int.class) {
            return "I";
        }
        if (c == long.class) {
            return "J";
        }
        if (c == float.class) {
            return "F";
        }
        if (c == double.class) {
            return "D";
        }
        return "V";
    }

    private void emitField(ClassFile.Member f) {
        if (f.name() == null || f.desc() == null) {
            out.line("// J2PC skipped a field with an invalid name or descriptor");
            return;
        }
        String mods = Modifiers.forField(f.access, opts);
        Object cv = f.constantValue();
        String fin = Modifiers.fieldFinal(f.access, cv != null);
        String type = types.ref(f.desc());
        StringBuilder line = new StringBuilder();
        if (!mods.isEmpty()) {
            line.append(mods).append(' ');
        }
        if (!fin.isEmpty()) {
            line.append(fin);
        }
        line.append(type).append(' ').append(names.field(cf.name(), f.name(), f.desc()));
        if (cv != null) {
            // The ConstantValue attribute holds the value of a constant field.
            line.append(" = ").append(literal(cv, f.desc()));
        } else if (needsInterfaceHolder() && f.isStatic()) {
            // The value is computed by the nested holder's initializer.
            line.append(" = __init.").append(names.field(cf.name(), f.name(), f.desc()));
        }
        line.append(';');
        out.line(line.toString());
    }

    private String literal(Object v, String desc) {
        if (v instanceof String) {
            return MethodEmitter.quote((String) v);
        }
        if (v instanceof Float) {
            float f = (Float) v;
            if (Float.isNaN(f)) {
                return "java.lang.Float.NaN";
            }
            return Float.toString(f) + "f";
        }
        if (v instanceof Long) {
            return v + "L";
        }
        if (v instanceof Double) {
            return v + "d";
        }
        if (v instanceof Integer) {
            switch (desc.charAt(0)) {
                case 'C':
                    return "(char) " + v;
                case 'Z':
                    return ((Integer) v) != 0 ? "true" : "false";
                default:
                    return v.toString();
            }
        }
        return "null";
    }

    private void emitMethod(ClassFile.Member m) {
        if (m.name() == null || m.desc() == null) {
            out.blank();
            out.line("// J2PC skipped a member with an invalid name or descriptor");
            return;
        }
        out.blank();
        writeBody(MethodEmitter.emit(cf, m, opts, names, types));
    }

    private void emitStaticInitializer() {
        ClassFile.Member clinit = null;
        for (ClassFile.Member m : cf.methods) {
            if ("<clinit>".equals(m.name())) {
                clinit = m;
            }
        }
        if (clinit == null) {
            return;
        }

        if (cf.isInterface()) {
            emitInterfaceInitializer(clinit);
            return;
        }

        out.blank();
        String code = MethodEmitter.emitStaticInitializer(cf, clinit, opts, names, types);
        int open = code.indexOf('{');
        int close = code.lastIndexOf('}');
        out.line("static {");
        if (open >= 0 && close > open) {
            String body = code.substring(open + 1, close);
            List<String> lines = new ArrayList<>();
            for (String line : body.split("\n")) {
                String trimmed = line.trim();
                if (trimmed.isEmpty()) {
                    continue;
                }
                lines.add(trimmed);
            }
            // A static initialiser must be able to complete normally (JLS 8.7).
            // When the body always throws, javac rejects the class; wrapping it in
            // `if (true)` keeps the behaviour and satisfies the rule.
            boolean cannotComplete = !lines.isEmpty()
                    && lines.get(lines.size() - 1).startsWith("throw ")
                    && !lines.stream().anyMatch(l -> l.startsWith("break"));
            if (cannotComplete) {
                out.line("if (true) {");
                out.indent();
            }
            for (String line : lines) {
                out.line(line);
            }
            if (cannotComplete) {
                out.outdent();
                out.line("}");
            }
        }
        out.line("}");
    }

    /**
     * An interface may not contain an initializer block, but bytecode gives it a
     * {@code <clinit>} whenever a constant field needs computation.
     *
     * <p>The body is moved into a nested holder class, which <em>is</em> allowed
     * inside an interface, and every constant field reads its value from there.
     * The holder is initialised by the first field initializer that touches it,
     * so the original ordering is preserved.</p>
     */
    private void emitInterfaceInitializer(ClassFile.Member clinit) {
        String holder = "__init";

        out.blank();
        out.line("final class " + holder + " {");
        out.indent();
        for (ClassFile.Member f : cf.fields) {
            if (f.isStatic() && f.name() != null && f.desc() != null) {
                out.line("static " + types.ref(f.desc()) + " "
                        + names.field(cf.name(), f.name(), f.desc()) + ";");
            }
        }
        out.blank();

        String code = MethodEmitter.emitStaticInitializer(cf, clinit, opts, names, types);
        int open = code.indexOf('{');
        int close = code.lastIndexOf('}');
        out.line("static {");
        if (open >= 0 && close > open) {
            for (String line : code.substring(open + 1, close).split("\n")) {
                String trimmed = line.trim();
                if (trimmed.isEmpty() || trimmed.equals("return;")) {
                    continue;
                }
                out.line(redirectOwnFields(trimmed, holder));
            }
        }
        out.line("}");
        out.outdent();
        out.line("}");

        out.blank();
        out.line("// the holder above initialises the constants of this interface");
    }

    /** True when this interface needs the nested holder for its constants. */
    private boolean needsInterfaceHolder() {
        if (!cf.isInterface()) {
            return false;
        }
        for (ClassFile.Member m : cf.methods) {
            if ("<clinit>".equals(m.name())) {
                return true;
            }
        }
        return false;
    }

    /**
     * Rewrites a reference to one of this interface's own fields into a reference
     * to the holder class.
     *
     * <p>Both {@code b.a_f2} and the fully qualified {@code unpackaged.b.a_f2} have
     * to be caught: the emitter writes the qualified form once the class has been
     * moved into a package, and an interface field is implicitly {@code final}, so
     * a missed redirect produces "cannot assign a value to static final".</p>
     *
     * <p>The match must also be anchored: a plain substring replace would corrupt
     * unrelated names, turning {@code java.lang.String} into
     * {@code java.__init.String} for an interface called {@code lang}.</p>
     */
    private String redirectOwnFields(String line, String holder) {
        String simple = types.simpleName(cf.name());
        String pkg = types.packageOf(cf.name());
        String out = line;
        if (!pkg.isEmpty()) {
            String qualified = pkg + "." + simple;
            java.util.regex.Pattern q = java.util.regex.Pattern.compile(
                    "(?<![\\w$.])" + java.util.regex.Pattern.quote(qualified) + "\\.");
            out = q.matcher(out).replaceAll(holder + ".");
        }
        java.util.regex.Pattern p = java.util.regex.Pattern.compile(
                "(?<![\\w$.])" + java.util.regex.Pattern.quote(simple) + "\\.");
        return p.matcher(out).replaceAll(holder + ".");
    }

    /**
     * Writes a method whose first line is the signature and whose last line is
     * the closing brace. Indentation is recomputed from the brace nesting, so
     * the emitter does not have to track it for the wrapper constructs it
     * inserts (the checked-exception guard, for example).
     */
    private void writeBody(String code) {
        int depth = 0;
        for (String line : code.split("\n", -1)) {
            String trimmed = line.trim();
            if (trimmed.isEmpty()) {
                out.blank();
                continue;
            }
            if (trimmed.startsWith("}")) {
                depth = Math.max(0, depth - 1);
            }
            for (int i = 0; i < depth; i++) {
                out.indent();
            }
            out.line(trimmed);
            for (int i = 0; i < depth; i++) {
                out.outdent();
            }
            depth += braceDelta(trimmed);
            if (depth < 0) {
                depth = 0;
            }
        }
    }

    /** Net brace count of a line, ignoring braces inside literals and comments. */
    private static int braceDelta(String line) {
        int delta = 0;
        char quote = 0;
        for (int i = 0; i < line.length(); i++) {
            char c = line.charAt(i);
            if (quote != 0) {
                if (c == '\\') {
                    i++;
                } else if (c == quote) {
                    quote = 0;
                }
                continue;
            }
            if (c == '"' || c == '\'') {
                quote = c;
            } else if (c == '/' && i + 1 < line.length() && line.charAt(i + 1) == '/') {
                break;
            } else if (c == '{') {
                delta++;
            } else if (c == '}') {
                delta--;
            }
        }
        return delta;
    }

    private String typeRef(String internalName) {
        return types.refInternal(internalName);
    }

    /** File name of the emitted compilation unit, including the mapped package. */
    public static String fileName(ClassFile cf, TypeMapper types) {
        return types.simpleName(cf.name()) + ".java";
    }
}
