package javax.microedition.midlet;

import javax.microedition.lcdui.Display;

import java.awt.BorderLayout;
import java.awt.Dimension;
import java.awt.event.WindowAdapter;
import java.awt.event.WindowEvent;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.atomic.AtomicReference;

import javax.swing.JFrame;
import javax.swing.JMenu;
import javax.swing.JMenuBar;
import javax.swing.JMenuItem;
import javax.swing.JOptionPane;
import javax.swing.JScrollPane;
import javax.swing.JTextArea;
import javax.swing.KeyStroke;
import javax.swing.SwingUtilities;

/**
 * Desktop host that runs a MIDlet inside a Swing window.
 *
 * <p>This is the entry point used by the launcher generated by J2PC. It is
 * deliberately small: it owns the window, forwards the lifecycle calls and
 * exposes the application properties that the JAD contributed.</p>
 */
public final class MIDletHost {

    private static final Map<String, String> PROPERTIES = new LinkedHashMap<>();
    private static final AtomicReference<MIDlet> CURRENT = new AtomicReference<>();
    private static JFrame frame;

    /** How long a shutdown may take before the JVM is halted outright. */
    private static final long SHUTDOWN_GRACE_MS = 3000;

    /** Guards against two shutdown requests racing (window close + notifyDestroyed). */
    private static final java.util.concurrent.atomic.AtomicBoolean EXITING =
            new java.util.concurrent.atomic.AtomicBoolean();

    private MIDletHost() {
    }

    public static void setProperty(String key, String value) {
        PROPERTIES.put(key, value);
    }

    public static void setProperties(Properties props) {
        for (String name : props.stringPropertyNames()) {
            PROPERTIES.put(name, props.getProperty(name));
        }
    }

    public static String getProperty(String key) {
        String v = PROPERTIES.get(key);
        return v == null ? "" : v;
    }

    public static Map<String, String> properties() {
        return PROPERTIES;
    }

    /** Runs the MIDlet on the Swing event thread and blocks until exit. */
    public static void run(MIDlet midlet, String title, String vendor, String version) {
        CURRENT.set(midlet);
        PROPERTIES.putIfAbsent("MIDlet-Name", title);
        PROPERTIES.putIfAbsent("MIDlet-Vendor", vendor);
        PROPERTIES.putIfAbsent("MIDlet-Version", version);

        SwingUtilities.invokeLater(() -> {
            frame = new JFrame(title + "  -  " + vendor + " " + version + "  [J2PC]");
            frame.setDefaultCloseOperation(JFrame.DO_NOTHING_ON_CLOSE);
            frame.setLayout(new BorderLayout());
            frame.addWindowListener(new WindowAdapter() {
                @Override
                public void windowClosing(WindowEvent e) {
                    requestExit(midlet);
                }
            });
            frame.setJMenuBar(buildMenuBar(midlet, title));
            Display.init(frame);
            frame.pack();
            frame.setMinimumSize(new Dimension(240, 320));
            frame.setLocationRelativeTo(null);
            frame.setVisible(true);
            try {
                midlet.startFromHost();
            } catch (MIDletStateChangeException e) {
                throw new RuntimeException(e);
            }
        });
    }

    /**
     * Menu bar with the two things a recompiled application needs but cannot draw
     * itself: a way out and a reminder of the key mapping.
     *
     * <p>Both live in a menu rather than on a key, because every key belongs to the
     * application — a game that uses {@code Esc} as "back" would be broken by a
     * host that took it.</p>
     */
    private static JMenuBar buildMenuBar(MIDlet midlet, String title) {
        JMenuBar bar = new JMenuBar();

        JMenu app = new JMenu("Application");
        JMenuItem quit = new JMenuItem("Quit");
        quit.setAccelerator(KeyStroke.getKeyStroke("control Q"));
        quit.addActionListener(e -> requestExit(midlet));
        app.add(quit);
        bar.add(app);

        JMenu help = new JMenu("Help");
        JMenuItem controls = new JMenuItem("Controls...");
        controls.setAccelerator(KeyStroke.getKeyStroke("F12"));
        controls.addActionListener(e -> showControls(title));
        help.add(controls);
        JMenuItem about = new JMenuItem("About J2PC");
        // The version is deliberately not read from the tool: a packaged
        // application carries only the runtime packages, so referencing the
        // compiler's own classes here would fail with NoClassDefFoundError.
        about.addActionListener(e -> JOptionPane.showMessageDialog(frame,
                "Recompiled J2ME application\n\n"
                        + title + "\n\n"
                        + "Generated by J2PC.\n"
                        + "The original bytecode was translated to Java, not emulated.",
                "About", JOptionPane.INFORMATION_MESSAGE));
        help.add(about);
        bar.add(help);

        return bar;
    }

    /** Shows the key mapping in a scrollable dialog. */
    private static void showControls(String title) {
        String text = "Keyboard\n"
                + "  Arrows / W A S D .............. move (UP, LEFT, DOWN, RIGHT)\n"
                + "  Enter, Space, Numpad 5 ........ FIRE / select\n"
                + "  Q or F1 ....................... GAME_A\n"
                + "  E or F2 ....................... GAME_B\n"
                + "  R or F3 ....................... GAME_C\n"
                + "  T or F4 ....................... GAME_D\n"
                + "  0-9 ........................... digits\n"
                + "  * and # ....................... star, pound\n"
                + "\n"
                + "Pointer\n"
                + "  Click and drag on the screen ... touch / stylus input\n"
                + "  The pointer is reported in the game's own coordinates,\n"
                + "  so a scaled window still taps the right spot.\n"
                + "\n"
                + "Window\n"
                + "  Ctrl+Q, menu Application > Quit  quit\n"
                + "  F12, menu Help > Controls ....... this list\n"
                + "\n"
                + "Not every application listens to every key: a game that only\n"
                + "reads the numeric keypad ignores the arrows, and one written\n"
                + "for a touch handset ignores the keyboard entirely.";
        JTextArea area = new JTextArea(text);
        area.setEditable(false);
        area.setFont(new java.awt.Font(java.awt.Font.MONOSPACED, java.awt.Font.PLAIN, 12));
        area.setCaretPosition(0);
        JScrollPane scroll = new JScrollPane(area);
        scroll.setPreferredSize(new Dimension(520, 380));
        JOptionPane.showMessageDialog(frame, scroll, "Controls - " + title,
                JOptionPane.INFORMATION_MESSAGE);
    }

    /**
     * Shuts the application down, whatever state it is in.
     *
     * <p>Three things can go wrong here, and all of them have been seen in real
     * suites: {@code destroyApp} throws, {@code destroyApp} blocks, or the suite
     * leaves a non-daemon thread running. A plain {@code System.exit} handles none
     * of them — the exception skips the exit, the block never returns, and the
     * thread keeps the JVM alive. So the shutdown runs on its own thread with a
     * deadline, and {@link Runtime#halt} finishes the job when the polite path
     * does not.</p>
     */
    static void requestExit(MIDlet midlet) {
        if (!EXITING.compareAndSet(false, true)) {
            return;
        }
        Thread shutdown = new Thread(() -> {
            try {
                midlet.destroyFromHost();
            } catch (Throwable ignored) {
                // A failing destroyApp must not keep the window alive.
            }
            SwingUtilities.invokeLater(() -> {
                if (frame != null) {
                    frame.dispose();
                }
            });
            // Give AWT a moment to close the window, then stop the JVM outright:
            // shutdown hooks installed by the application may block, and the
            // process must still end.
            try {
                Thread.sleep(150);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
            System.exit(0);
        }, "j2pc-shutdown");
        shutdown.setDaemon(true);
        shutdown.start();

        // Last resort: if System.exit is stuck in a shutdown hook, halt.
        Thread watchdog = new Thread(() -> {
            try {
                Thread.sleep(SHUTDOWN_GRACE_MS);
            } catch (InterruptedException e) {
                return;
            }
            Runtime.getRuntime().halt(0);
        }, "j2pc-watchdog");
        watchdog.setDaemon(true);
        watchdog.start();
    }

    public static MIDlet current() {
        return CURRENT.get();
    }
}
